function stripModuleSyntax(code) {
  return code
    .replace(/import\s+(?:type\s+)?(?:[\s\S]*?from\s+)?['"][^'"]+['"]\s*;?/g, "")
    .replace(/^export\s+(const|let|function|async function|class)\s+/gm, "$1 ")
    .replace(/^export\s+\{[^}]+\}\s+from\s+['"][^'"]+['"];?\s*$/gm, "")
    .replace(/^export\s+\{[^}]+\};?\s*$/gm, "")
    .replace(/^export\s+default\s+/gm, "");
}

function writeBundle() {
  const missing = jsFiles.filter((file) => !fs.existsSync(path.join(root, file)));
  if (missing.length) throw new Error(`Missing JS: ${missing.join(", ")}`);

  const bundle = jsFiles
    .map((file) => {
      const code = stripModuleSyntax(fs.readFileSync(path.join(root, file), "utf8"));
      return `/* ── ${file} ── */\n${code}`;
    })
    .join("\n\n");

  const out = path.join(root, "js/bundle.js");
  fs.writeFileSync(out, bundle);
  console.log("Wrote", rel(out), `(${(bundle.length / 1024).toFixed(1)} KB)`);
}

