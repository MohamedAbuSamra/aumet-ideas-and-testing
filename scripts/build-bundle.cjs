/**
 * Builds css/app.css, js/generated/templates.js, and js/bundle.js
 * so index.html works from file:// (GitHub Pages / double-click).
 *
 * Run: node scripts/build-bundle.cjs
 */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");

function walk(dir, match) {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full, match));
    else if (match(entry.name, full)) out.push(full);
  }
  return out;
}

function rel(file) {
  return path.relative(root, file).split(path.sep).join("/");
}

function toTemplateLiteral(html) {
  return html
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\$\{/g, "\\${");
}

function writeTemplates() {
  const htmlFiles = walk(path.join(root, "features"), (name) => name.endsWith(".html"));
  const screens = {};
  let shellHtml = "";

  htmlFiles.forEach((file) => {
    const id = path.basename(file, ".html");
    const html = fs.readFileSync(file, "utf8");
    if (id === "shell") shellHtml = html;
    else screens[id] = html;
  });

  const screenEntries = Object.entries(screens)
    .map(([id, html]) => `  ${JSON.stringify(id)}: \`${toTemplateLiteral(html)}\``)
    .join(",\n");

  const generated = `/** Generated by scripts/build-bundle.cjs — do not edit. */\nexport const shellHtml = \`${toTemplateLiteral(shellHtml)}\`;\n\nexport const screenTemplates = {\n${screenEntries}\n};\n`;
  const out = path.join(root, "js/generated/templates.js");
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, generated);
  console.log("Wrote", rel(out), `(${Object.keys(screens).length} screens)`);
}

function writeCss() {
  const preferred = [
    "css/tokens.css",
    "features/shell/shell.css",
    "features/mobile/shared/legacy.css",
    "features/mobile/shared/chrome.css",
    "features/mobile/onboarding/landing/landing.css",
    "features/mobile/onboarding/verify-otp/verify-otp.css",
    "features/mobile/onboarding/home/home.css",
    "features/mobile/onboarding/my-pharmacy/my-pharmacy.css",
    "features/mobile/onboarding/shared/complete-profile.css",
    "features/mobile/login/login/login.css",
    "features/website/pos/shared/pulse.css",
  ];
  const seen = new Set(preferred);
  const extras = walk(path.join(root, "features"), (name) => name.endsWith(".css"))
    .map(rel)
    .filter((file) => !seen.has(file))
    .sort();
  const files = [...preferred, ...extras];
  const missing = files.filter((file) => !fs.existsSync(path.join(root, file)));
  if (missing.length) throw new Error(`Missing CSS: ${missing.join(", ")}`);

  const banner = "/* Generated by scripts/build-bundle.cjs — edit feature CSS, then npm run build. */\n\n";
  const css = banner + files
    .map((file) => `/* ── ${file} ── */\n${fs.readFileSync(path.join(root, file), "utf8")}`)
    .join("\n\n");
  const out = path.join(root, "css/app.css");
  fs.writeFileSync(out, css.endsWith("\n") ? css : `${css}\n`);
  console.log("Wrote", rel(out), `(${(css.length / 1024).toFixed(1)} KB)`);
}

